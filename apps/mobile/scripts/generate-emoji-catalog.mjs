#!/usr/bin/env node
// Regenerates lib/emoji-catalog-data.ts from the unicode-emoji-json and
// emojilib packages (both MIT). Usage:
//   npm pack unicode-emoji-json emojilib && tar xzf unicode-emoji-json-*.tgz
//   mkdir el && tar xzf emojilib-*.tgz -C el
//   node scripts/generate-emoji-catalog.mjs ./package ./el/package
// Emoji newer than MAX_EMOJI_VERSION are skipped so every option renders on
// the iOS versions the member app supports.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const MAX_EMOJI_VERSION = 15.0;
const [unicodeDir, emojilibDir] = process.argv.slice(2);
if (!unicodeDir || !emojilibDir) {
  console.error('usage: generate-emoji-catalog.mjs <unicode-emoji-json dir> <emojilib dir>');
  process.exit(1);
}

const groups = JSON.parse(readFileSync(join(unicodeDir, 'data-by-group.json'), 'utf8'));
const keywords = JSON.parse(readFileSync(join(emojilibDir, 'dist/emoji-en-US.json'), 'utf8'));
const ICONS = {
  smileys_emotion: '😀', people_body: '👋', animals_nature: '🌿', food_drink: '🍔',
  travel_places: '✈️', activities: '⚽', objects: '💡', symbols: '❤️', flags: '🏳️',
};
const LABELS = { smileys_emotion: 'Smileys', people_body: 'People', animals_nature: 'Nature', food_drink: 'Food',
  travel_places: 'Travel', activities: 'Activities', objects: 'Objects', symbols: 'Symbols', flags: 'Flags' };

const categories = groups.map((group) => ({
  id: group.slug,
  label: LABELS[group.slug] ?? group.name,
  icon: ICONS[group.slug] ?? group.emojis[0].emoji,
  emojis: group.emojis
    .filter((item) => Number(item.emoji_version) <= MAX_EMOJI_VERSION)
    .map((item) => {
      const words = new Set(item.name.toLowerCase().split(/[\s:_,-]+/).filter(Boolean));
      for (const word of keywords[item.emoji] ?? []) {
        for (const part of word.toLowerCase().split(/[\s_,-]+/)) if (part) words.add(part);
      }
      return [item.emoji, item.name.toLowerCase(), [...words].join(' ')];
    }),
}));

const total = categories.reduce((n, c) => n + c.emojis.length, 0);
const out = `// Generated by scripts/generate-emoji-catalog.mjs - do not edit by hand.
// Source: unicode-emoji-json + emojilib (MIT). ${total} emoji, Emoji ${MAX_EMOJI_VERSION} and older.
// Each entry is [emoji, name, search words].

export type EmojiEntry = readonly [emoji: string, name: string, search: string];

export interface EmojiCategoryData {
  id: string;
  label: string;
  icon: string;
  emojis: readonly EmojiEntry[];
}

export const EMOJI_CATEGORY_DATA: readonly EmojiCategoryData[] = ${JSON.stringify(categories)};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '../lib/emoji-catalog-data.ts');
writeFileSync(target, out);
console.log(`wrote ${total} emoji to ${target}`);
