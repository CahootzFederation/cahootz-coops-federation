#!/usr/bin/env node
/**
 * Renders the Commons Street road pieces, trees and street details from KayKit
 * City Builder Bits (CC0, Kay Lousberg, art-source/kaykit) at the exact angle
 * the app draws the street. Houses and shops stay the app's own drawings.
 *
 *   pnpm -F @cahootz/mobile exec node scripts/render-kaykit-sprites.cjs
 *
 * Writes assets/street/kaykit/*.png and components/street/kaykit-sprites.ts.
 * Needs Chrome (Playwright's `chrome` channel) and internet for three.js.
 * Dev-only: nothing here ships in the app except the images and the index.
 */
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('@playwright/test');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'art-source', 'kaykit');
const OUT = path.join(ROOT, 'assets', 'street', 'kaykit');
const INDEX = path.join(ROOT, 'components', 'street', 'kaykit-sprites.ts');
const R = Math.PI / 2;

async function main() {
    // A road tile at rotation 0 runs along j; a curved corner at 0 joins +i and +j;
  // the T at 0 joins -j, +j and +i (checked from a top-down render).
  const specs = {
    'road-straight-i': { parts: [{ model: 'road_straight', rot: R }] },
    'road-straight-j': { parts: [{ model: 'road_straight' }] },
    'road-crossing-i': { parts: [{ model: 'road_straight_crossing', rot: R }] },
    'road-t-east': { parts: [{ model: 'road_tsplit' }] },
    'road-corner-ij': { parts: [{ model: 'road_corner_curved' }] },
    'road-corner-mi-j': { parts: [{ model: 'road_corner_curved', rot: -R }] },
    'road-corner-i-mj': { parts: [{ model: 'road_corner_curved', rot: R }] },
    'road-corner-mi-mj': { parts: [{ model: 'road_corner_curved', rot: 2 * R }] },
    tree: { parts: [{ model: 'bush', scale: 2.4 }] },
    streetlight: { parts: [{ model: 'streetlight' }] },
    car: { parts: [{ model: 'car_sedan', rot: R }] },
  };
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  const browser = await chromium.launch({ channel: 'chrome', args: ['--use-gl=angle', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage();
  page.on('pageerror', (e) => console.error('page error:', e.message));
  await page.route('http://kaykit.local/**', (route) => {
    const rel = new URL(route.request().url()).pathname;
    const file = rel === '/' ? path.join(__dirname, 'kaykit', 'render.html') : path.join(SRC, rel.replace(/^\/models\//, ''));
    if (!fs.existsSync(file)) return route.fulfill({ status: 404, body: 'missing' });
    const type = file.endsWith('.html') ? 'text/html' : file.endsWith('.png') ? 'image/png' : file.endsWith('.gltf') ? 'model/gltf+json' : 'application/octet-stream';
    return route.fulfill({ status: 200, body: fs.readFileSync(file), contentType: type });
  });
  await page.goto('http://kaykit.local/');
  await page.waitForFunction(() => window.__ready === true, null, { timeout: 60_000 });

  const index = [];
  let bytes = 0;
  for (const [name, spec] of Object.entries(specs)) {
    const r = await page.evaluate((s) => window.renderSprite(s), spec);
    const png = Buffer.from(r.dataUrl.split(',')[1], 'base64');
    fs.writeFileSync(path.join(OUT, `${name}.png`), png);
    bytes += png.length;
    // Sizes in points (rendered at 2x).
    index.push(`  '${name}': { source: require('@/assets/street/kaykit/${name}.png'), w: ${r.w / 2}, h: ${r.h / 2}, ax: ${r.ax / 2}, ay: ${r.ay / 2} },`);
  }
  await browser.close();

  fs.writeFileSync(
    INDEX,
    `// Generated by scripts/render-kaykit-sprites.cjs from KayKit City Builder Bits (CC0). Do not edit by hand.\n` +
      `// w/h: image size in points. ax/ay: where the model's ground point sits inside the image.\n` +
      `export const KAYKIT_SPRITES = {\n${index.join('\n')}\n} as const;\n\nexport type KayKitSpriteName = keyof typeof KAYKIT_SPRITES;\n`,
  );
  console.log(`Rendered ${index.length} images, ${(bytes / 1024).toFixed(0)} KB total.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
